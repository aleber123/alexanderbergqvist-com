#!/usr/bin/env node
/**
 * Generates src/data/namnsdagar.ts from the Födelsedagar app's name-day
 * table, so the website and the app always show the same names.
 *
 *   node scripts/gen-namnsdagar.mjs [path/to/name_day_data.dart]
 *
 * Default source: ~/Downloads/birthday_app/lib/data/name_day_data.dart
 *
 * Only the SWEDISH tables are read (`nameDaysSe` and
 * `nameDaysSeAdditions2027`). The Norwegian and Finnish lists are
 * licensed by their almanac publishers and must not be published here;
 * Danish is intentionally left out for now.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src =
  process.argv[2] ?? join(homedir(), 'Downloads/birthday_app/lib/data/name_day_data.dart');
const dart = readFileSync(src, 'utf8');

function readMap(name) {
  const start = dart.indexOf(`Map<String, List<String>> ${name} = {`);
  if (start < 0) throw new Error(`${name} not found in ${src}`);
  const end = dart.indexOf('};', start);
  const body = dart.slice(start, end);
  const out = {};
  const re = /'(\d\d-\d\d)':\s*\[([^\]]*)\]/g;
  let m;
  while ((m = re.exec(body))) {
    const names = [...m[2].matchAll(/'([^']+)'/g)].map((x) => x[1]);
    if (out[m[1]]) throw new Error(`duplicate key ${m[1]} in ${name}`);
    out[m[1]] = names;
  }
  return out;
}

const base = readMap('nameDaysSe');
const add2027 = readMap('nameDaysSeAdditions2027');

const nBase = Object.values(base).flat().length;
const nAdd = Object.values(add2027).flat().length;
if (Object.keys(base).length < 350 || nBase < 600) {
  throw new Error(`Suspiciously small table: ${Object.keys(base).length} days, ${nBase} names`);
}

const fmt = (obj) =>
  '{\n' +
  Object.keys(obj)
    .sort()
    .map((k) => `  '${k}': ${JSON.stringify(obj[k]).replace(/"/g, "'")},`)
    .join('\n') +
  '\n}';

const ts = `// GENERATED by scripts/gen-namnsdagar.mjs — do not edit by hand.
// Source: the Födelsedagar app's name_day_data.dart (generated ${new Date().toISOString().slice(0, 10)}).
//
// Svenska Akademiens namnlängd as listed on sv.wikipedia
// ("Lista över namnsdagar i Sverige i datumordning", incl. the 2022
// changes), plus the six names Namnlängdskommittén adds from 2027
// (Isof, "Nya namn i almanackan", 2025-01-14).
// Only the date → names facts are used; all prose on the site is our own.
//
// Keys are 'MM-DD'. Days without a name (e.g. 1 jan, 25 dec, 29 feb)
// are omitted.

/** Names per day, valid 2022–2026 (and the base list from 2027 on). */
export const NAMNSDAGAR: Record<string, string[]> = ${fmt(base)};

/** Names added to the almanac from 2027. */
export const TILLAGG_2027: Record<string, string[]> = ${fmt(add2027)};
`;
const out = join(root, 'src/data/namnsdagar.ts');
writeFileSync(out, ts);
console.log(`Wrote ${out}: ${Object.keys(base).length} days, ${nBase} names + ${nAdd} from 2027`);
